"""A norns sprite sheet (16 grey levels) -> frames of 4-bit palette indices for the 120x120 UI (src/ui/ec_palette.h).

The default is Elasticat for norns' intro logo (Elasticat/images/q7logoanim.png: 55 frames of 128x64, 10 fps, played
once, 5.5 s; elasticat.lua draw_intro_screen). The 128-px frames are cropped to the 120 grid (--crop-x: 4 = the 4
columns either side, where only the opening frames' glitch streaks reach; the logo and its caption sit in x 13..113),
never scaled. Grey levels map to the nearest step of the ramp BG SHADE L3 L5 L8 L12 L15; pure white (255, the logo's
flash frames) maps to ACC.

  python3 -I sprite_to_c.py --bin out.bin [sheet.png]          one index per byte, frame after frame (host/mock_ux2.c)
  python3 -I sprite_to_c.py --c out.h [sheet.png]              a C array, two pixels per byte (high nibble first), for
                                                               the firmware build
  python3 -I sprite_to_c.py --gif out.gif --palette palette.json [--fps 10] [--cat] [sheet.png]
                                                               an animated GIF of the 120x120 screen, 4x

It also takes Elasticat/images/dancingcat.png (the CAT: 12 frames of 128x64, 10 fps at 120 BPM): its ground (level 22)
maps to SHADE and its black outlines to BG. 0.6.1: SHADE is the ground's key (the firmware's ec_scr_cat() keys it out:
the stage and its beams show there) and BG the outline (drawn BLACK); the cat's art spans 64x61 of the 120x64 frame, so
it is drawn at 1x (2x would not fit the 120 grid). The ramp's greys below are only the source levels' matching points:
the themes' BG and SHADE are pure black now (src/ui/ec_palette.c).
"""
import argparse
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(HERE, "../../../Elasticat/images/q7logoanim.png")
# palette slots (src/ui/ec_palette.h) and the default theme's grey value of each ramp step
BG, SHADE, L3, L5, L8, L12, L15, ACC = 0, 14, 2, 3, 4, 5, 6, 7
RAMP = [(0x0B, BG), (0x1C, SHADE), (0x34, L3), (0x5E, L5), (0x9A, L8), (0xCF, L12), (0xF6, L15)]
SCREEN, Y0 = 120, 28                       # the frame's place on the 120x120 screen: centred, y 28..91


def level_to_slot(v):
    if v >= 250:
        return ACC
    return min(RAMP, key=lambda r: abs(r[0] - v))[1]


def frames(path, fw, fh, crop_x):
    im = Image.open(path).convert("L")
    n = im.width // fw
    w = fw - 2 * crop_x
    out = []
    for f in range(n):
        fr = im.crop((f * fw + crop_x, 0, f * fw + crop_x + w, fh))
        out.append(bytes(level_to_slot(v) for v in fr.getdata()))
    return out, w, fh


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sheet", nargs="?", default=DEFAULT)
    ap.add_argument("--frame-w", type=int, default=128)
    ap.add_argument("--frame-h", type=int, default=64)
    ap.add_argument("--crop-x", type=int, default=4)
    ap.add_argument("--bin")
    ap.add_argument("--c")
    ap.add_argument("--gif")
    ap.add_argument("--palette", help="palette.json (ec_mock_ux2) for --gif")
    ap.add_argument("--name", default="ec_intro")
    ap.add_argument("--fps", type=int, default=10, help="--gif: frames per second (norns: 10 for both sheets)")
    ap.add_argument("--cat", action="store_true", help="--gif: the CAT's ground (SHADE, the art's own dark grey)")
    a = ap.parse_args()
    fr, w, h = frames(a.sheet, a.frame_w, a.frame_h, a.crop_x)
    if a.bin:
        with open(a.bin, "wb") as f:
            for x in fr:
                f.write(x)
    if a.c:
        with open(a.c, "w") as f:
            f.write("/* generated by tools/mockups/sprite_to_c.py from %s: palette slots (src/ui/ec_palette.h), two pixels\n"
                    " * per byte, high nibble first */\n" % os.path.basename(a.sheet))
            f.write("#define %s_FRAMES %d\n#define %s_W %d\n#define %s_H %d\n#define %s_FPS 10\n"
                    % (a.name.upper(), len(fr), a.name.upper(), w, a.name.upper(), h, a.name.upper()))
            f.write("static const unsigned char %s[%d][%d] = {\n" % (a.name, len(fr), w * h // 2))
            for x in fr:
                packed = bytes((x[i] << 4) | x[i + 1] for i in range(0, len(x), 2))
                f.write("    {" + ",".join(str(b) for b in packed) + "},\n")
            f.write("};\n")
    if a.gif:
        pal = json.load(open(a.palette))["themes"]["CREAM"]
        flat = []
        for c in pal:                     # as the LCD shows it (RGB565), so the GIF matches the PNGs
            v = int(c[1:], 16)
            r, g, b = v >> 16 & 255, v >> 8 & 255, v & 255
            flat += [(r >> 3) * 255 // 31, (g >> 2) * 255 // 63, (b >> 3) * 255 // 31]
        flat += [0] * (768 - len(flat))
        x0 = (SCREEN - w) // 2
        ims = []
        for x in fr:
            buf = bytearray([SHADE if a.cat else BG]) * (SCREEN * SCREEN)
            for y in range(h):
                buf[(Y0 + y) * SCREEN + x0:(Y0 + y) * SCREEN + x0 + w] = x[y * w:(y + 1) * w]
            im = Image.frombytes("P", (SCREEN, SCREEN), bytes(buf))
            im.putpalette(flat)
            ims.append(im.resize((SCREEN * 4, SCREEN * 4), Image.NEAREST))
        ims[0].save(a.gif, save_all=True, append_images=ims[1:], duration=1000 // a.fps, loop=0, optimize=False)
    print("%d frames of %dx%d%s" % (len(fr), w, h, "".join(" -> " + p for p in (a.bin, a.c, a.gif) if p)))


if __name__ == "__main__":
    main()
